"""Phase 7: preregistered, paired, source-fingerprinted RareBench evaluation.

No patient predictions are generated by this module. It audits real outputs from
src.evaluate_external; no use of disease labels in inference. All confidence
intervals are exploratory case-resampled intervals, not medical efficacy claims.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import random
from collections import Counter
from pathlib import Path

METHODS = frozenset({
    "overlap", "semantic", "quality_semantic", "tfidf", "logistic",
    "random_forest", "xgboost", "mlp", "DeepRare_external",
})
METRICS = ("top1", "top5", "mrr", "candidate_recall", "disease_coverage")
RESULT_COLUMNS = frozenset({
    "case_id", "cohort", "method", "true_disease_id", "known_disease",
    "rank", "top1", "top5", "reciprocal_rank", "retrieval_k",
})
CASE_COLUMNS = frozenset({"case_id", "disease_id", "hpo_ids"})
PLAN_SCHEMA = "raregen_phase7_preregistered_v1"


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_csv(path, required):
    with Path(path).open(newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        if not reader.fieldnames or len(reader.fieldnames) != len(set(reader.fieldnames)):
            raise ValueError(f"Missing or repeated CSV column names: {path}")
        if not set(required).issubset(reader.fieldnames):
            raise ValueError(f"Missing required CSV columns in {path}: {sorted(set(required)-set(reader.fieldnames))}")
        rows = list(reader)
    if not rows:
        raise ValueError(f"CSV contains no data rows: {path}")
    if any(None in row or any(value is None for value in row.values()) for row in rows):
        raise ValueError(f"Malformed/extra CSV fields in {path}")
    return rows


def read_cases(path):
    rows = load_csv(path, CASE_COLUMNS)
    found = {}
    for r in rows:
        case_id = r["case_id"].strip()
        disease = r["disease_id"].strip()
        cohort = r.get("cohort", "").strip() or "unspecified"
        terms = r["hpo_ids"].split(";")
        if not case_id or not disease or not terms or any(not t or t.strip() != t for t in terms):
            raise ValueError(f"Empty/invalid case, disease, or HPO terms: {case_id!r}")
        if case_id in found:
            raise ValueError(f"Duplicate case ID: {case_id}")
        if cohort == "ALL":
            raise ValueError("ALL is a reserved cohort aggregation label")
        if any(len(t) != 10 or not t.startswith("HP:") or not t[3:].isdigit() for t in terms):
            raise ValueError(f"Invalid canonical seven-digit HPO ID: {case_id}")
        if len(set(terms)) != len(terms):
            raise ValueError(f"Duplicate HPO terms in case: {case_id}")
        found[case_id] = {"case_id": case_id, "disease_id": disease,
                          "cohort": cohort, "hpo_count": len(terms)}
    return found


def read_model_manifest(path, model_path=None):
    manifest = json.loads(Path(path).read_text(encoding="utf-8"))
    fingerprint = manifest.get("artifact_sha256", "")
    if not isinstance(fingerprint, str) or len(fingerprint) != 64 or any(c not in "0123456789abcdef" for c in fingerprint):
        raise ValueError("Missing or invalid verified-model SHA-256")
    if manifest.get("source", {}).get("kind") != "hpo_sqlite_v2_aspect_P":
        raise ValueError("Phase 7 requires a phenotype-only, source-verified SQLite training snapshot")
    if model_path is not None and sha256(model_path) != fingerprint:
        raise ValueError("Model bytes differ from verified training manifest")
    return manifest


def read_dataset_manifest(path, cases_path, n):
    manifest = json.loads(Path(path).read_text(encoding="utf-8"))
    if manifest.get("dataset") != "chenxz/RareBench":
        raise ValueError("Unknown dataset provenance: expected published RareBench")
    if manifest.get("sha256") != sha256(cases_path) or manifest.get("eligible_total") != n:
        raise ValueError("RareBench CSV SHA-256 or eligible count differs from source manifest")
    archive = manifest.get("archive_sha256", "")
    if not isinstance(archive, str) or len(archive) != 64 or any(c not in "0123456789abcdef" for c in archive):
        raise ValueError("Missing/invalid RareBench archive SHA-256")
    return manifest


def freeze(cases_path, dataset_manifest_path, model_manifest_path, methods, *, model_path=None,
           seed=42, retrieval_k=40, max_cases=0):
    """Create a pre-evaluation protocol before inspecting generated predictions."""
    methods = list(methods)
    if not methods or len(set(methods)) != len(methods) or any(m not in METHODS for m in methods):
        raise ValueError("Unsupported/duplicate/empty method selection")
    if "DeepRare_external" in methods:
        raise ValueError("Authentic DeepRare predictions must be verified separately before inclusion")
    if "overlap" not in methods or len(methods) < 2:
        raise ValueError("Phase 7 paired comparison requires overlap and at least one other method")
    if not isinstance(retrieval_k, int) or retrieval_k < 1:
        raise ValueError("retrieval_k must be positive")
    if not isinstance(seed, int) or not isinstance(max_cases, int) or max_cases < 0:
        raise ValueError("Invalid seed/max_cases")
    cases = read_cases(cases_path)
    dataset = read_dataset_manifest(dataset_manifest_path, cases_path, len(cases))
    model = read_model_manifest(model_manifest_path, model_path)
    case_ids = list(cases)
    if max_cases:
        case_ids = case_ids[:max_cases]
    if not case_ids:
        raise ValueError("Pre-registered evaluation subset is empty")
    cohort_counts = dict(sorted(Counter(cases[c]["cohort"] for c in case_ids).items()))
    return {
        "schema": PLAN_SCHEMA,
        "research_scope": "retrospective_published_cases_not_independent_prospective_clinical_validation",
        "case_sha256": sha256(cases_path),
        "case_count": len(case_ids),
        "full_dataset_case_count": len(cases),
        "case_ids": case_ids,
        "cohorts": cohort_counts,
        "dataset_archive_sha256": dataset["archive_sha256"],
        "dataset_manifest_sha256": sha256(dataset_manifest_path),
        "model_artifact_sha256": model["artifact_sha256"],
        "model_profile_sha256": model.get("profile_sha256"),
        "model_manifest_sha256": sha256(model_manifest_path),
        "methods": methods,
        "ml_retrieval_k": retrieval_k,
        "selection_first_n": max_cases,
        "bootstrap_seed": seed,
        "bootstrap_unit": "independent_case_id_within_cohort",
        "warning": "Raw rank scores are not calibrated probabilities; HPO annotation publication overlap may remain",
    }


def checked_rank(row):
    raw = row["rank"].strip()
    if raw == "":
        return None
    if not raw.isdecimal() or int(raw) < 1:
        raise ValueError(f"Malformed rank for {row['case_id']} / {row['method']}: {raw!r}")
    return int(raw)


def _flag(value, label):
    if value not in ("0", "1", 0, 1):
        raise ValueError(f"Invalid {label} indicator: {value!r}")
    return int(value)


def audit_rows(rows, cases, plan):
    """Require exactly one correctly scored row per case/method and identical cohorts."""
    selected = set(plan["case_ids"])
    by_key = {}
    expected = {(c, method) for c in selected for method in plan["methods"]}
    for r in rows:
        key = (r["case_id"].strip(), r["method"].strip())
        if not r["retrieval_k"].isdecimal() or int(r["retrieval_k"]) != plan["ml_retrieval_k"]:
            raise ValueError(f"Retrieval candidate limit differs from frozen protocol for {key}")
        if key not in expected or key in by_key:
            raise ValueError(f"Unexpected or duplicate case/method result: {key}")
        case = cases[key[0]]
        if r["cohort"].strip() != case["cohort"] or r["true_disease_id"].strip() != case["disease_id"]:
            raise ValueError(f"Cohort or ground truth differs for {key}")
        rank = checked_rank(r)
        top1, top5 = _flag(r["top1"], "top1"), _flag(r["top5"], "top5")
        known = _flag(r["known_disease"], "known_disease")
        value = float(r["reciprocal_rank"])
        if not math.isfinite(value) or not 0 <= value <= 1:
            raise ValueError(f"Invalid reciprocal rank: {key}")
        expected_reciprocal = 1 / rank if rank else 0
        if (top1 != int(rank == 1) or top5 != int(rank is not None and rank <= 5)
                or not math.isclose(value, expected_reciprocal, abs_tol=1e-9, rel_tol=0)):
            raise ValueError(f"Rank / metric mismatch: {key}")
        by_key[key] = {"case_id": key[0], "method": key[1], "cohort": case["cohort"],
                       "true_disease_id": case["disease_id"], "known_disease": known,
                       "rank": rank, "top1": top1, "top5": top5,
                       "mrr": expected_reciprocal, "candidate_recall": int(rank is not None),
                       "disease_coverage": known}
    if set(by_key) != expected:
        raise ValueError(f"Incomplete paired evaluation: missing {len(expected-set(by_key))} case/method rows")
    for case_id in selected:
        coverages = {by_key[case_id, method]["known_disease"] for method in plan["methods"]}
        if len(coverages) != 1:
            raise ValueError(f"Conflicting disease-coverage flags across methods for {case_id}")
    return by_key


def _ci(values, rng, replicates):
    n = len(values)
    if n == 0:
        raise ValueError("Cannot bootstrap zero cases")
    if replicates < 100:
        raise ValueError("At least 100 bootstrap replicates required")
    estimates = sorted(sum(values[rng.randrange(n)] for _ in range(n)) / n for _ in range(replicates))
    return (estimates[int(0.025 * (replicates - 1))], estimates[int(0.975 * (replicates - 1))])


def _rng(seed, *labels):
    text = json.dumps([seed, *labels], separators=(",", ":"))
    h = hashlib.sha256(text.encode("utf-8")).hexdigest()
    return random.Random(int(h[:16], 16))


def summarize(by_key, plan, *, replicates=2000):
    """Recomputed cohort metrics + stratified paired percentile-bootstrap intervals."""
    if replicates < 100 or replicates > 100000:
        raise ValueError("Bootstrap replicates must be 100 to 100000")
    cohorts = ["ALL", *sorted(plan["cohorts"])]
    summary, paired, errors, details = [], [], [], []
    for case_id in plan["case_ids"]:
        for method in plan["methods"]:
            r = by_key[case_id, method]
            if r["rank"] == 1:
                reason = "top1_hit"
            elif r["rank"] is not None and r["rank"] <= 5:
                reason = "rank_2_to_5"
            elif r["rank"] is not None:
                reason = "rank_beyond_top5"
            elif not r["known_disease"]:
                reason = "truth_outside_model_disease_universe"
            else:
                reason = "truth_not_in_returned_ranked_list"
            details.append({"case_id": case_id, "cohort": r["cohort"], "method": method,
                            "true_disease_id": r["true_disease_id"], "known_disease": r["known_disease"],
                            "rank": r["rank"] or "", "top1": r["top1"], "top5": r["top5"],
                            "reciprocal_rank": r["mrr"], "error_category": reason})
    for cohort in cohorts:
        ids = [c for c in plan["case_ids"] if cohort == "ALL" or by_key[c, plan["methods"][0]]["cohort"] == cohort]
        n = len(ids)
        if not n:
            raise ValueError(f"Empty selected cohort {cohort}")
        for method in plan["methods"]:
            subset = [by_key[c, method] for c in ids]
            for field in METRICS:
                values = [r[field] for r in subset]
                low, high = _ci(values, _rng(plan["bootstrap_seed"], cohort, method, field), replicates)
                summary.append({"cohort": cohort, "method": method, "metric": field,
                                "n": n, "estimate": sum(values)/n, "ci95_low": low,
                                "ci95_high": high, "ci_method": "case_percentile_bootstrap_exploratory"})
            counts = Counter(d["error_category"] for d in details if d["method"] == method
                             and (cohort == "ALL" or d["cohort"] == cohort))
            for reason in sorted(counts):
                errors.append({"cohort": cohort, "method": method, "n": n,
                               "error_category": reason, "count": counts[reason],
                               "fraction": counts[reason]/n})
            if method == "overlap":
                continue
            if "overlap" not in plan["methods"]:
                continue
            for field in METRICS:
                if field == "disease_coverage":
                    continue  # Same knowledge universe for all methods: trivial zero difference.
                values = [by_key[c, method][field] - by_key[c, "overlap"][field] for c in ids]
                low, high = _ci(values, _rng(plan["bootstrap_seed"], cohort, method, field, "paired"), replicates)
                paired.append({"cohort": cohort, "method": method, "baseline": "overlap",
                               "metric": field, "n": n, "difference": sum(values)/n,
                               "ci95_low": low, "ci95_high": high,
                               "ci_method": "paired_case_percentile_bootstrap_exploratory"})
    return details, summary, paired, errors


def verify_legacy_summary(legacy_rows, by_key, plan):
    """Ensure previous evaluation aggregate agrees with audited individual rows."""
    expected_cohorts = {"ALL", *plan["cohorts"]}
    expected_keys = {(c, m) for c in expected_cohorts for m in plan["methods"]}
    found = set()
    for row in legacy_rows:
        key = (row["cohort"], row["method"])
        if key not in expected_keys or key in found:
            raise ValueError(f"Unmatched/duplicate legacy summary row: {key}")
        found.add(key)
        cohort, method = key
        ids = [c for c in plan["case_ids"] if cohort == "ALL" or by_key[c, method]["cohort"] == cohort]
        n = len(ids)
        if not row["n"].isdecimal() or int(row["n"]) != n:
            raise ValueError(f"Legacy summary cohort size mismatch: {key}")
        for column, field in (("top1", "top1"), ("top5", "top5"),
                              ("mrr", "mrr"), ("candidate_recall", "candidate_recall"),
                              ("disease_coverage", "known_disease")):
            observed = float(row[column]); actual = sum(by_key[c, method][field] for c in ids)/n
            if not math.isfinite(observed) or not math.isclose(observed, actual, abs_tol=1e-9, rel_tol=0):
                raise ValueError(f"Legacy summary {column} differs from case records: {key}")
    if found != expected_keys:
        raise ValueError(f"Missing legacy summary rows: {len(expected_keys-found)}")


def write_csv(path, rows):
    if not rows:
        return None
    path = Path(path)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return sha256(path)


def run_audit(*, cases_path, results_path, legacy_summary_path, plan_path,
              dataset_manifest_path, model_manifest_path, out_dir,
              model_path=None, replicates=2000):
    plan = json.loads(Path(plan_path).read_text(encoding="utf-8"))
    if plan.get("schema") != PLAN_SCHEMA:
        raise ValueError("Missing/unsupported pre-registered Phase 7 evaluation plan")
    cases = read_cases(cases_path)
    dataset = read_dataset_manifest(dataset_manifest_path, cases_path, len(cases))
    model = read_model_manifest(model_manifest_path, model_path)
    if (plan.get("case_sha256") != sha256(cases_path)
            or plan.get("dataset_manifest_sha256") != sha256(dataset_manifest_path)
            or plan.get("model_manifest_sha256") != sha256(model_manifest_path)
            or plan.get("model_artifact_sha256") != model["artifact_sha256"]
            or plan.get("dataset_archive_sha256") != dataset["archive_sha256"]):
        raise ValueError("Frozen plan no longer matches downloaded cases, dataset or model")
    ids = list(cases)[:plan["selection_first_n"] or None]
    if plan["case_ids"] != ids or plan["case_count"] != len(ids):
        raise ValueError("Case selection changed after evaluation plan was frozen")
    if (set(plan["methods"]) - METHODS or not plan["methods"]
            or "DeepRare_external" in plan["methods"]):
        raise ValueError("Plan includes unsupported/unverified evaluation methods")
    rows = load_csv(results_path, RESULT_COLUMNS)
    by_key = audit_rows(rows, cases, plan)
    legacy = load_csv(legacy_summary_path, {"cohort", "method", "n", "top1", "top5", "mrr", "candidate_recall", "disease_coverage"})
    verify_legacy_summary(legacy, by_key, plan)
    details, summary, paired, errors = summarize(by_key, plan, replicates=replicates)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    names = {"phase7_case_audit.csv": details, "phase7_cohort_metrics.csv": summary,
             "phase7_paired_effects.csv": paired, "phase7_error_analysis.csv": errors}
    hashes = {}
    for name, data in names.items():
        if data:
            hashes[name] = write_csv(out/name, data)
    provenance = {
        "schema": PLAN_SCHEMA,
        "status": "audited_observed_external_results_not_prospective_clinical_validation",
        "case_count": len(plan["case_ids"]),
        "cohorts": plan["cohorts"],
        "methods": plan["methods"],
        "bootstrap_replicates": replicates,
        "bootstrap_seed": plan["bootstrap_seed"],
        "case_sha256": sha256(cases_path),
        "dataset_archive_sha256": dataset["archive_sha256"],
        "model_artifact_sha256": model["artifact_sha256"],
        "model_profile_sha256": model.get("profile_sha256"),
        "phase7_plan_sha256": sha256(plan_path),
        "input_results_sha256": sha256(results_path),
        "legacy_summary_sha256": sha256(legacy_summary_path),
        "output_csv_sha256": hashes,
        "rank_universe_note": "ML top-40 retrieval vs ontology baseline full disease universe; candidate_recall is observed truth in returned list, not a common retrieval recall",
        "honesty": "Paired exploratory bootstrap confidence intervals; no clinical significance, prospective independence, calibrated disease probabilities or matched DeepRare run",
    }
    (out/"phase7_provenance.json").write_text(json.dumps(provenance, indent=2, sort_keys=True)+"\n", encoding="utf-8")
    return provenance


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    command = p.add_subparsers(dest="command", required=True)
    f = command.add_parser("freeze", help="Create frozen protocol before running patient ranking")
    f.add_argument("--cases", required=True)
    f.add_argument("--dataset-manifest", required=True)
    f.add_argument("--model-manifest", required=True)
    f.add_argument("--model", default=None)
    f.add_argument("--methods", nargs="+", required=True)
    f.add_argument("--out", default="results/phase7_plan.json")
    f.add_argument("--seed", type=int, default=42)
    f.add_argument("--retrieval-k", type=int, default=40)
    f.add_argument("--max-cases", type=int, default=0)
    a = command.add_parser("audit", help="Reject inconsistent outcomes and publish cohort uncertainty")
    a.add_argument("--cases", required=True)
    a.add_argument("--results", required=True)
    a.add_argument("--legacy-summary", required=True)
    a.add_argument("--plan", required=True)
    a.add_argument("--dataset-manifest", required=True)
    a.add_argument("--model-manifest", required=True)
    a.add_argument("--model", default=None)
    a.add_argument("--out-dir", default="results")
    a.add_argument("--replicates", type=int, default=2000)
    args = p.parse_args(argv)
    if args.command == "freeze":
        plan = freeze(args.cases, args.dataset_manifest, args.model_manifest,
                      args.methods, model_path=args.model, seed=args.seed,
                      retrieval_k=args.retrieval_k, max_cases=args.max_cases)
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        if out.exists():
            raise FileExistsError(f"Refusing to overwrite pre-registered protocol: {out}")
        out.write_text(json.dumps(plan, indent=2, sort_keys=True)+"\n", encoding="utf-8")
        print(f"FROZEN Phase 7 protocol: {out}, {plan['case_count']} cases, {plan['methods']}")
    else:
        provenance = run_audit(cases_path=args.cases, results_path=args.results,
                              legacy_summary_path=args.legacy_summary, plan_path=args.plan,
                              dataset_manifest_path=args.dataset_manifest,
                              model_manifest_path=args.model_manifest, model_path=args.model,
                              out_dir=args.out_dir, replicates=args.replicates)
        print(json.dumps(provenance, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
